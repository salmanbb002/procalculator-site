#!/usr/bin/env node
// Splits assets/js/calculators.js (one 148KB+ bundle containing every
// calculator's logic) into one small file per tool at assets/js/calc/<id>.js,
// each containing only the shared utility helpers + that tool's own
// CALCULATORS['<id>'] block. This lets calculator/<id>.html pages load ~2-5KB
// of JS instead of the entire bundle for every other tool on the site.
//
// The generic calculator.html fallback page (used for tool slugs that don't
// have a dedicated static page) still loads the full calculators.js bundle,
// since it doesn't know which tool it needs until the URL is read client-side.
//
// Re-run this any time a calculator's logic changes in calculators.js, or a
// new CALCULATORS['id'] block is added:
//   node scripts/split-calculators.mjs

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const src = readFileSync(path.join(ROOT, 'assets/js/calculators.js'), 'utf8');

const HEADER_MARKER = 'const CALCULATORS = {};';
const headerEnd = src.indexOf(HEADER_MARKER) + HEADER_MARKER.length;
if (headerEnd < HEADER_MARKER.length) {
  throw new Error(`Could not find "${HEADER_MARKER}" in calculators.js`);
}
const header = src.slice(0, headerEnd) + '\n';
const body = src.slice(headerEnd);

const blockOpenRe = /CALCULATORS\['([a-z0-9-]+)'\]\s*=\s*\{/g;
const blocks = new Map();
let m;
while ((m = blockOpenRe.exec(body))) {
  const id = m[1];
  const start = m.index;
  let depth = 0;
  let j = m.index + m[0].length - 1; // position of the opening '{'
  for (; j < body.length; j++) {
    if (body[j] === '{') depth++;
    else if (body[j] === '}') {
      depth--;
      if (depth === 0) break;
    }
  }
  let end = j + 1;
  if (body[end] === ';') end++;

  // Pull in a preceding "/* ---- Name ---- */" comment line, if present.
  const pre = body.slice(0, start);
  const commentMatch = /(\/\*[^\n]*\*\/\s*\n)$/.exec(pre);
  const blockStart = commentMatch ? commentMatch.index : start;
  blocks.set(id, body.slice(blockStart, end) + '\n');
}

const outDir = path.join(ROOT, 'assets/js/calc');
mkdirSync(outDir, { recursive: true });

// Clean out any stale per-tool files for calculators that no longer exist.
const currentIds = new Set(blocks.keys());
for (const f of readdirSync(outDir)) {
  const id = f.replace(/\.js$/, '');
  if (!currentIds.has(id)) console.warn('stale (not regenerated by this run):', f);
}

let written = 0;
for (const [id, block] of blocks) {
  writeFileSync(path.join(outDir, `${id}.js`), header + '\n' + block, 'utf8');
  written++;
}

console.log(`Split ${written} calculators into assets/js/calc/*.js (from a ${(src.length / 1024).toFixed(1)}KB bundle).`);
console.log('Reminder: each calculator/<id>.html page should load /assets/js/calc/<id>.js, not the full bundle.');
